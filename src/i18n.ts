export const UI = { es, en };
export type UILang = keyof typeof UI;
export const UI_LANGS = Object.keys(UI) as UILang[];
/** Cada idioma de la app con su nombre en ese idioma, para reconocerlo aunque no lo leas. */
export const UI_LANG_NAMES: Record<UILang, string> = { es: 'Español', en: 'English' };

export const makeT = (lang: UILang) => (key: UIKey) => UI[lang][key] ?? UI.en[key] ?? key;

/** Textos fijos que aparecen en el propio CV. */
const CV_LABELS: Record<string, { present: string; ongoing: string }> = {
  es: { present: 'Hoy', ongoing: 'Actualidad' },
  en: { present: 'Present', ongoing: 'Current' },
  fr: { present: "Aujourd'hui", ongoing: 'En cours' },
  de: { present: 'Heute', ongoing: 'Laufend' },
  it: { present: 'Oggi', ongoing: 'In corso' },
  pt: { present: 'Atual', ongoing: 'Em curso' },
  ca: { present: 'Avui', ongoing: 'Actualitat' },
  gl: { present: 'Hoxe', ongoing: 'Actualidade' },
};

export const cvLabel = (lang: string, key: 'present' | 'ongoing') =>
  (CV_LABELS[lang.split('-')[0]] ?? CV_LABELS.en)[key];

export const DEFAULT_TITLES: Record<SectionKind, LText> = {
  text: { es: 'sobre mí', en: 'about me' },
  entries: { es: 'experiencia', en: 'experience' },
  pairs: { es: 'idiomas', en: 'languages' },
  skills: { es: 'habilidades', en: 'skills' },
};

export function langName(code: string, uiLang: string) {
  try {
    const n = new Intl.DisplayNames([uiLang], { type: 'language' }).of(code);
    return n ? n.charAt(0).toUpperCase() + n.slice(1) : code;
  } catch {
    return code;
  }
}
